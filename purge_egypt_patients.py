"""
Remove tracked entities from the Egypt Hypertension & Diabetes programme.

Intended for clearing a demo cohort that was generated by an older version of
move_patients_egypt.py, so a fresh run is not mixed in with data built under
different rules.

It lists what it would delete and stops. Deleting anything needs --confirm
DELETE, spelled exactly:

    python purge_egypt_patients.py                      # list only
    python purge_egypt_patients.py --confirm DELETE     # actually delete

Deletion is permanent. There is no undo.
"""

import argparse
import sys

from dhis2 import RequestException as DHIS2RequestException
from logzero import logger

from tracker_common import load_api

TARGET_ENV_PREFIX = 'EGYPT_NCD'
PROGRAM = 'pMIglSEqPGS'
CONFIRM_PHRASE = 'DELETE'


def fetch_enrolled_teis(api, org_unit_root):
    """Every tracked entity enrolled in the programme, newest first."""
    uids, page = [], 1

    while True:
        response = api.get('tracker/trackedEntities', params={
            'program': PROGRAM,
            'orgUnit': org_unit_root,
            'ouMode': 'DESCENDANTS',
            'fields': 'trackedEntity,createdAt',
            'page': page,
            'pageSize': 500,
        }).json()

        instances = response.get('instances', response.get('trackedEntities', []))
        if not instances:
            break

        uids.extend(i['trackedEntity'] for i in instances)
        if len(instances) < 500:
            break
        page += 1

    return uids


def delete_in_chunks(api, uids, chunk_size=50):
    """Delete via the tracker import endpoint, which takes a payload."""
    deleted = failed = 0

    for i in range(0, len(uids), chunk_size):
        chunk = uids[i:i + chunk_size]
        payload = {'trackedEntities': [{'trackedEntity': uid} for uid in chunk]}
        try:
            response = api.post('tracker', params={
                'async': 'false',
                'importStrategy': 'DELETE',
            }, json=payload)
            result = response.json()
            if result.get('status') == 'ERROR':
                failed += len(chunk)
                for report in result.get('validationReport', {}).get('errorReports', [])[:3]:
                    logger.error(f"  {report.get('errorCode')}: {report.get('message')}")
            else:
                deleted += len(chunk)
                logger.info(f"  deleted {deleted}/{len(uids)}")
        except DHIS2RequestException as e:
            failed += len(chunk)
            logger.error(f"  chunk failed: {e}")

    return deleted, failed


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--confirm', default=None,
                        help=f"Type {CONFIRM_PHRASE} to actually delete. "
                             "Without it, the script only reports what it found.")
    parser.add_argument('--org-unit', default=None,
                        help='Root org unit to search under (default: the root of '
                             'the hierarchy)')
    args = parser.parse_args()

    api = load_api(TARGET_ENV_PREFIX, 'target (Egypt NCD)')
    logger.info(f"Target DHIS2 {api.version}")

    org_unit = args.org_unit
    if org_unit is None:
        roots = api.get('organisationUnits', params={
            'filter': 'level:eq:1', 'fields': 'id,name', 'paging': 'false',
        }).json()['organisationUnits']
        if not roots:
            logger.error("Could not find the root org unit; pass --org-unit.")
            sys.exit(2)
        org_unit = roots[0]['id']
        logger.info(f"Searching under {roots[0]['name']} ({org_unit})")

    uids = fetch_enrolled_teis(api, org_unit)
    logger.info(f"Found {len(uids)} tracked entities enrolled in {PROGRAM}")

    if not uids:
        return

    if args.confirm != CONFIRM_PHRASE:
        logger.warning(
            f"Nothing deleted. {len(uids)} patients and all their visits would be "
            f"removed permanently. Re-run with --confirm {CONFIRM_PHRASE} to proceed."
        )
        print(f"\nFirst few that would be deleted: {', '.join(uids[:5])}")
        return

    logger.warning(f"Deleting {len(uids)} tracked entities. This cannot be undone.")
    deleted, failed = delete_in_chunks(api, uids)
    logger.info(f"Deleted {deleted}, failed {failed}")


if __name__ == '__main__':
    main()
